// Compatibility suite for dsh-go-usage against the INSTALLED DeepSeek Harness
// (0.2.x line). Proves the two contract surfaces the plugin depends on:
//
//   host/    index.js + typert.host.js — module linking, Config, the Typert
//            host manifest against the real loader validator, and the session
//            aggregation / pricing / settings behaviour.
//   client/  client.js — the browser bundle registers, mounts its Remote
//            contribution, registers both slots, and renders.
//
//   node test/compat.mjs            # run every suite
//   node test/compat.mjs --keep     # keep the generated harnesses for inspection
//
// Resolution: the suites must import the exact `@deepseek-ai/*` packages the
// running DSH hands to plugins. Rather than symlinking those packages into a
// harness (a privilege some sandboxes deny) this runner writes one two-line
// re-export shim per package — `export * from <real lib/index.js>` — under
// <pluginRoot>/.compat/node_modules. Shims are ordinary files, so the harness
// needs no install and no link privilege, and every real package keeps
// resolving its own dependencies from its own tree.
//
// Package discovery order: DSH_NODE_MODULES, this package's own node_modules
// (when its devDependencies are installed), then the running interpreter's
// global DSH install.
import { createRequire } from "node:module";
import { accessSync, constants, cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pluginRoot = resolve(here, "..");
const harnessRoot = join(pluginRoot, ".compat");
const keep = process.argv.includes("--keep");

/** Packages the suites (or the plugin itself) import directly. */
const SHIMMED = [
  "cordis",
  "schemastery",
  "dsh-typert-protocol",
  "dsh-typert-loader",
  "dsh-typert-registry",
  "dsh-credentials",
];

const PLUGIN_FILES = ["index.js", "go-prices.js", "typert.host.js", "client.js", "package.json"];

/** Locate the `@deepseek-ai/*` packages the running DSH resolves for plugins. */
function locateDshPackages() {
  const binDir = dirname(process.execPath);
  const candidates = [
    process.env.DSH_NODE_MODULES,
    join(pluginRoot, "node_modules", "@deepseek-ai"),
    // nvm-for-windows layout: <nodeDir>/node_modules/...
    join(binDir, "node_modules", "@deepseek-ai", "dsh", "node_modules", "@deepseek-ai"),
    // POSIX / nvm-posix layout
    join(binDir, "..", "lib", "node_modules", "@deepseek-ai", "dsh", "node_modules", "@deepseek-ai"),
    join(binDir, "..", "node_modules", "@deepseek-ai", "dsh", "node_modules", "@deepseek-ai"),
  ];
  for (const candidate of candidates) {
    if (!candidate) continue;
    try {
      accessSync(join(candidate, "dsh-typert-loader", "package.json"), constants.R_OK);
      return resolve(candidate);
    } catch {
      /* try the next candidate */
    }
  }
  console.error("compat: cannot locate the installed @deepseek-ai packages (need dsh-typert-loader).");
  console.error("        Set DSH_NODE_MODULES to the directory holding dsh-typert-loader, cordis, …");
  process.exit(1);
}

const dshPackages = locateDshPackages();
const requireFromDsh = createRequire(join(dshPackages, "noop.cjs"));

/** Read a package's real version for the run header. */
function versionOf(name) {
  try {
    return JSON.parse(readFileSync(join(dshPackages, name, "package.json"), "utf8")).version;
  } catch {
    return "?";
  }
}

/**
 * Write one re-export shim so the harness resolves `@deepseek-ai/<name>` to the
 * installed package without a symlink or a copy.
 * @param {string} nodeModulesDir - harness root that holds `node_modules`.
 * @param {string} name - package name after the `@deepseek-ai/` scope.
 */
function writeShim(nodeModulesDir, name) {
  let entry;
  try {
    entry = requireFromDsh.resolve(`@deepseek-ai/${name}`);
  } catch (error) {
    throw new Error(`compat: cannot resolve @deepseek-ai/${name} from ${dshPackages}: ${error.message}`);
  }
  const url = pathToFileURL(entry).href;
  const pkgDir = join(nodeModulesDir, "@deepseek-ai", name);
  mkdirSync(pkgDir, { recursive: true });
  writeFileSync(
    join(pkgDir, "package.json"),
    JSON.stringify(
      { name: `@deepseek-ai/${name}`, version: "0.0.0-compat-shim", type: "module", main: "index.js", exports: { ".": "./index.js" } },
      null,
      2,
    ) + "\n",
  );
  writeFileSync(
    join(pkgDir, "index.js"),
    [
      `// Generated by test/compat.mjs — re-exports the installed @deepseek-ai/${name}.`,
      `export * from ${JSON.stringify(url)};`,
      `import * as real from ${JSON.stringify(url)};`,
      "export default real.default;",
      "",
    ].join("\n"),
  );
}

/** Materialize one suite directory with the plugin files it needs. */
function buildHarness(suite, files) {
  const dir = join(harnessRoot, suite);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const file of files) cpSync(join(pluginRoot, file), join(dir, file));
  return dir;
}

// ---- harness: shared shims ----------------------------------------------
rmSync(harnessRoot, { recursive: true, force: true });
mkdirSync(join(harnessRoot, "node_modules", "@deepseek-ai"), { recursive: true });
for (const name of SHIMMED) writeShim(join(harnessRoot, "node_modules"), name);

const suites = [
  { name: "host", dir: buildHarness("host", PLUGIN_FILES), script: "host.mjs" },
  { name: "client", dir: buildHarness("client", ["client.js"]), script: "client.mjs" },
];
for (const suite of suites) cpSync(join(here, suite.script), join(suite.dir, suite.script));

console.log(`compat: DSH packages = ${dshPackages}`);
console.log(`compat: cordis ${versionOf("cordis")} · dsh-typert-protocol ${versionOf("dsh-typert-protocol")} · dsh-typert-loader ${versionOf("dsh-typert-loader")}\n`);

let failed = 0;
for (const suite of suites) {
  console.log(`=== ${suite.name} ===`);
  try {
    // Each suite runs its checks at import time and reports a `summary` rather
    // than exiting, so one crashed suite cannot hide the other's results.
    const module = await import(pathToFileURL(join(suite.dir, suite.script)).href);
    if (!module.summary || module.summary.failed > 0) {
      failed += 1;
      if (module.summary) console.log(`FAIL  ${suite.name} suite: ${module.summary.failedNames.join("; ")}`);
    }
  } catch (error) {
    failed += 1;
    console.error(`FAIL  ${suite.name} suite crashed :: ${error && error.stack ? error.stack : error}`);
  }
  console.log("");
}

if (!keep) rmSync(harnessRoot, { recursive: true, force: true });
else console.log(`compat: harnesses kept at ${harnessRoot}`);
console.log(failed === 0 ? "compat: ALL SUITES PASSED" : `compat: ${failed} SUITE(S) FAILED`);
process.exit(failed === 0 ? 0 : 1);
